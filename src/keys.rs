use crate::bunker::{self, BunkerConnection};
use nostr_sdk::prelude::{Keys, PublicKey, ToBech32};

pub fn generate_new_nsec() -> String {
    let keys = Keys::generate();
    keys.secret_key()
        .to_bech32()
        .expect("bech32 encoding of a fresh key cannot fail")
}

pub fn parse_pubkey(pubkey: &str) -> Result<String, String> {
    let pk = crate::utils::parse_public_key(pubkey)?;
    Ok(pk.to_hex())
}

pub fn hex_to_npub(hex: &str) -> Result<String, String> {
    let pk = PublicKey::from_hex(hex.trim()).map_err(|e| e.to_string())?;
    pk.to_bech32().map_err(|e| e.to_string())
}

pub fn npub_to_hex(npub: &str) -> Result<String, String> {
    let pk = PublicKey::parse(npub.trim()).map_err(|e| e.to_string())?;
    Ok(pk.to_hex())
}

pub fn nsec_to_hex(nsec: &str) -> Result<String, String> {
    let keys = Keys::parse(nsec.trim()).map_err(|e| e.to_string())?;
    Ok(keys.secret_key().to_secret_hex())
}

/// Validate a credential and return the user's public key (hex).
///
/// Accepts a private key (`nsec1…` or hex) or a `bunker://` URI. For bunkers
/// this performs (or reuses) the NIP-46 handshake. Prefer [`connect_bunker`]
/// for new bunker logins: it also returns the canonical URI to persist.
pub async fn verify_nsec(nsec: &str, client_nsec: Option<&str>) -> Result<String, String> {
    let credential = nsec.trim();
    if bunker::is_bunker_uri(credential) {
        let session = bunker::connect(credential, client_nsec, &[]).await?;
        return Ok(session.user_pubkey.to_hex());
    }
    if bunker::is_nostrconnect_uri(credential) {
        return Err(
            "nostrconnect:// URIs are generated by this app. Paste a bunker:// URI from your signer, or use the QR pairing."
                .to_string(),
        );
    }
    let keys = Keys::parse(credential).map_err(|e| format!("Invalid private key: {e}"))?;
    Ok(keys.public_key().to_hex())
}

/// Establish a `bunker://` session and describe it for persistence.
pub async fn connect_bunker(
    uri: &str,
    client_nsec: Option<&str>,
) -> Result<BunkerConnection, String> {
    let session = bunker::connect(uri, client_nsec, &[]).await?;
    Ok(bunker::connection_of(&session))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_valid_nsec() {
        let nsec = generate_new_nsec();
        assert!(nsec.starts_with("nsec1"));
        assert!(Keys::parse(&nsec).is_ok());
        assert_ne!(generate_new_nsec(), nsec);
    }

    #[test]
    fn hex_npub_roundtrip() {
        let keys = Keys::generate();
        let hex = keys.public_key().to_hex();
        let npub = hex_to_npub(&hex).unwrap();
        assert!(npub.starts_with("npub1"));
        assert_eq!(npub_to_hex(&npub).unwrap(), hex);
        assert_eq!(npub_to_hex(&format!(" {npub} ")).unwrap(), hex);
        assert_eq!(parse_pubkey(&npub).unwrap(), hex);
    }

    #[test]
    fn hex_to_npub_rejects_bad_input() {
        assert!(hex_to_npub("zz").is_err());
        assert!(npub_to_hex("npub1zz").is_err());
        assert!(nsec_to_hex("nsec1zz").is_err());
    }

    #[test]
    fn nsec_to_hex_matches_key() {
        let keys = Keys::generate();
        let nsec = keys.secret_key().to_bech32().unwrap();
        assert_eq!(
            nsec_to_hex(&nsec).unwrap(),
            keys.secret_key().to_secret_hex()
        );
        // hex secret is accepted too
        assert_eq!(
            nsec_to_hex(&keys.secret_key().to_secret_hex()).unwrap(),
            keys.secret_key().to_secret_hex()
        );
    }

    #[tokio::test]
    async fn verify_nsec_accepts_private_keys() {
        let keys = Keys::generate();
        let nsec = keys.secret_key().to_bech32().unwrap();
        assert_eq!(
            verify_nsec(&nsec, None).await.unwrap(),
            keys.public_key().to_hex()
        );
        assert_eq!(
            verify_nsec(&format!("  {nsec}\n"), None).await.unwrap(),
            keys.public_key().to_hex()
        );
        assert_eq!(
            verify_nsec(&keys.secret_key().to_secret_hex(), None)
                .await
                .unwrap(),
            keys.public_key().to_hex()
        );
    }

    #[tokio::test]
    async fn verify_nsec_rejects_garbage_and_nostrconnect() {
        let err = verify_nsec("hello", None).await.unwrap_err();
        assert!(err.contains("Invalid private key"), "{err}");
        let err = verify_nsec("nostrconnect://abc?relay=wss://r", None)
            .await
            .unwrap_err();
        assert!(err.contains("bunker://"), "{err}");
        let err = verify_nsec("bunker://nothex", None).await.unwrap_err();
        assert!(err.contains("Invalid bunker URI"), "{err}");
    }
}
